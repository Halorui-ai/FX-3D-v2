# -*- coding: utf-8 -*-
"""Generate all gridded tracing crops in one go (0.3 m/px, 10 m grid)."""
import os, grid, geo

W = {
    "zD_a": (-1650, -290, -1150, 0), "zD_b": (-1650, -20, -1150, 280),
    "zF_a": (-590, -290, -60, 0), "zF_b": (-590, -20, -60, 280),
    "zA_a": (-1650, 270, -1150, 550), "zA_b": (-1650, 530, -1150, 820),
    "zB_a": (-1130, 270, -630, 550), "zB_b": (-1130, 530, -630, 830),
    "zC_a": (-590, 270, -40, 540), "zC_b": (-590, 500, -40, 760),
    "zK_a": (410, -290, 910, 0), "zK_b": (410, -20, 910, 280),
    "zL_a": (900, -290, 1420, 0), "zL_b": (900, -20, 1420, 280),
    "zM_a": (1420, -290, 1930, 0), "zM_b": (1420, -20, 1930, 280),
    "zGN_a": (420, 290, 910, 520), "zGN_b": (420, 490, 910, 720),
    "zGS_a": (440, 690, 910, 900), "zGS_b": (440, 870, 910, 1090),
}
for k, (u0, s0, u1, s1) in W.items():
    im = grid.window(u0, s0, u1, s1, 0.3)
    grid.draw_grid(im, u0, s0, 0.3, 10, 50)
    grid.save(im, os.path.join(geo.ROOT, "docs", "check", k + ".jpg"))
    print(k, im.shape)
